/* Shared with the still assets: the palette is Claude.md section 15, and the
   background plate is generated by the same function that draws the feature
   graphic, so the video and the listing cannot drift apart. */

export const FPS = 30;
export const WIDTH = 1920;
export const HEIGHT = 1080;

export const COLORS = {
  accent: "#e8c547",
  accent2: "#c47a3a",
  cream: "#e8e4dc",
  white: "#ffffff",
  ink: "#100e0c",
};

/* Avenir Next is resolved from the system, which is safe because rendering
   happens locally on the machine that built the screenshots. */
export const FONT = '"Avenir Next", -apple-system, BlinkMacSystemFont, sans-serif';

/* Phone geometry in the 1920x1080 frame. The source captures are 786x1601. */
export const PHONE = {
  /* Taller than the frame on purpose: a portrait phone shown whole inside
     1080px is too small to read, and unreadable app content is the one thing a
     promo video cannot afford. It bleeds off the top and bottom instead. */
  height: 1240,
  get width() {
    return Math.round(this.height * (786 / 1601));
  },
  radius: 34,
  frame: 9,
};

export const sec = (s: number) => Math.round(s * FPS);
